/* Physical blocks recovered from the Topaz GPL platform headers. */
#define QTN_TOPAZ_SYSCTL_BASE			0xe0000000
#define QTN_TOPAZ_SYSCTL_CTRL_MASK		0x0008
#define QTN_TOPAZ_SYSCTL_CTRL			0x000c
#define QTN_TOPAZ_SWITCH_BASE			0xe1000000
#define QTN_TOPAZ_HBM_BASE			(QTN_TOPAZ_SWITCH_BASE + 0x20000)
