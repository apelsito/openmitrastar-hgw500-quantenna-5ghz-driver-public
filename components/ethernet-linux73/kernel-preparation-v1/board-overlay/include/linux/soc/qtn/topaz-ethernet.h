#define QTN_TOPAZ_EMAC0_BASE			0xed000000
#define QTN_TOPAZ_EMAC1_BASE			0xe8000000

/* OEM Topaz kernel SRAM B2 is dead after handoff.  Reserve its final 8 KiB
 * for the EMAC rings.  Under RUBY_MMAP_FLIP the CPU must use the fixed
 * uncached SRAM alias; mapping the cached alias through ioremap creates a
 * vmalloc address that cold MMUv2 cannot refill safely.
 */
#define QTN_TOPAZ_EMAC_DESC_SRAM_CPU		0x8801e000
#define QTN_TOPAZ_EMAC_DESC_SRAM_NOCACHE	0x6001e000
#define QTN_TOPAZ_EMAC_DESC_SRAM_BUS		0x8001e000
#define QTN_TOPAZ_EMAC_DESC_SRAM_SIZE		0x00002000

#define QTN_TOPAZ_IRQ_TQE			5
#define QTN_TOPAZ_IRQ_EMAC0			19
#define QTN_TOPAZ_IRQ_EMAC1			20
#define QTN_TOPAZ_IRQ_HBM			21

